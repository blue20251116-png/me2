// Shared by generation and formatting. No API calls or global monkeypatches.
function normalizeVoice(text) {
  return String(text || '').replace(/\r/g, '').replace(/\\n/g, '\n')
    .split('\n').map(line => line.trim()).join('\n')
    .replace(/\n{3,}/g, '\n\n').trim();
}

